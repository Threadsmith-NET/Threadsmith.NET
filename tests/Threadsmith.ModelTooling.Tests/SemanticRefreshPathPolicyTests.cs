namespace Threadsmith.ModelTooling.Tests;

using Threadsmith.Core;
using Threadsmith.DotNet;
using Xunit;

/// <summary>Verifies the watcher filters that keep build output churn from starting refreshes.</summary>
public static class SemanticRefreshPathPolicyTests
{
    /// <summary>Preserves ordinary and explicitly loaded source while excluding known test build outputs.</summary>
    [Fact]
    public static void GeneratedTestSources_AreIgnoredOnlyUnderObj()
    {
        var root = Path.GetFullPath("repository");
        string[] names = ["SelfRegisteredExtensions.cs", "XunitAutoGeneratedEntryPoint.cs"];
        var generatedPaths = names.Select(name => Path.Combine(root, "Project", "obj", "Debug", "net10.0", name)).ToArray();
        var sourcePaths = names.Select(name => Path.Combine(root, "Project", name)).ToArray();
        var customInput = Path.Combine(root, "Project", "obj", "CustomInput.cs");
        var inventory = new SemanticRefreshInventory(
            generatedPaths.Concat(sourcePaths).Append(customInput).ToHashSet(),
            new HashSet<string>(),
            new HashSet<string>(),
            new HashSet<string>());

        Assert.All(generatedPaths, path => Assert.Equal(SemanticInputKind.None, SemanticRefreshPathPolicy.Classify(root, path, inventory)));
        Assert.All(sourcePaths, path => Assert.Equal(SemanticInputKind.Source, SemanticRefreshPathPolicy.Classify(root, path, inventory)));
        Assert.Equal(SemanticInputKind.Source, SemanticRefreshPathPolicy.Classify(root, customInput, inventory));
    }

    /// <summary>Preserves watcher coverage when directory topology can change.</summary>
    [Fact]
    public static void WatcherRestart_RequiresDirectoryChangeOrUncertainty()
    {
        Assert.False(SemanticRefreshPathPolicy.RequiresWatcherRestart(SemanticFileChangeKind.Renamed, directoryExists: false, watchesDirectory: false));
        Assert.True(SemanticRefreshPathPolicy.RequiresWatcherRestart(SemanticFileChangeKind.Created, directoryExists: true, watchesDirectory: false));
        Assert.True(SemanticRefreshPathPolicy.RequiresWatcherRestart(SemanticFileChangeKind.Deleted, directoryExists: false, watchesDirectory: true));
        Assert.True(SemanticRefreshPathPolicy.RequiresWatcherRestart(SemanticFileChangeKind.Uncertain, directoryExists: false, watchesDirectory: false));
    }
}
